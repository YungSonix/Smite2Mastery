const fs = require('fs');
const path = require('path');

const root = process.cwd();
const dataDir = path.join(root, 'app', 'data');
const voiceRoot =
  fs.existsSync(path.join(dataDir, 'VoiceAudio'))
    ? path.join(dataDir, 'VoiceAudio')
    : path.join(dataDir, 'Voice Audio');
const outFile = path.join(root, 'lib', 'voxManifest.generated.js');
const skinOutFile = path.join(root, 'lib', 'voxSkinManifest.generated.js');

const AUDIO_EXT = /\.(wav|mp3|m4a)$/i;

function normalizeKey(name) {
  return String(name || '')
    .toLowerCase()
    .replace(/[^a-z0-9]/g, '');
}

function listAudioFiles(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir, { withFileTypes: true })
    .filter((d) => d.isFile() && AUDIO_EXT.test(d.name))
    .map((d) => d.name)
    .sort((a, b) => a.localeCompare(b));
}

function collectSubfoldersWithAudio(skinPath) {
  const subfolders = {};
  if (!fs.existsSync(skinPath)) return subfolders;

  const entries = fs.readdirSync(skinPath, { withFileTypes: true });
  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    const files = listAudioFiles(path.join(skinPath, entry.name));
    if (files.length) subfolders[entry.name] = { files };
  }
  return subfolders;
}

function collectBaseManifest() {
  const manifest = {};
  if (!fs.existsSync(voiceRoot)) return manifest;

  const godDirs = fs
    .readdirSync(voiceRoot, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort((a, b) => a.localeCompare(b));

  for (const god of godDirs) {
    const files = listAudioFiles(path.join(voiceRoot, god, 'Skin00_Base', 'VOX'));
    if (!files.length) continue;
    manifest[normalizeKey(god)] = {
      folder: god,
      files: files.map((name) => ({ name })),
    };
  }
  return manifest;
}

/** All god/skin audio subfolders — keyed by god folder name (e.g. `Da_Ji`). */
function collectSkinManifest() {
  const manifest = {};
  if (!fs.existsSync(voiceRoot)) return manifest;

  const godDirs = fs
    .readdirSync(voiceRoot, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort((a, b) => a.localeCompare(b));

  for (const god of godDirs) {
    const godPath = path.join(voiceRoot, god);
    const skinDirs = fs
      .readdirSync(godPath, { withFileTypes: true })
      .filter((d) => d.isDirectory())
      .map((d) => d.name)
      .sort((a, b) => a.localeCompare(b));

    for (const skinFolder of skinDirs) {
      const subfolders = collectSubfoldersWithAudio(path.join(godPath, skinFolder));
      if (!Object.keys(subfolders).length) continue;
      if (!manifest[god]) manifest[god] = {};
      manifest[god][skinFolder] = { subfolders };
    }
  }
  return manifest;
}

function writeManifestModule(outPath, exportName, manifest) {
  const body = JSON.stringify(manifest, null, 2);
  const lines = [
    '// Auto-generated by scripts/generate-vox-manifest.js',
    '// Metadata only — playback uses GitHub raw URLs (no bundled require()).',
    '// Do not edit manually.',
    `export const ${exportName} = ${body};`,
    '',
    `export default ${exportName};`,
    '',
  ];
  fs.writeFileSync(outPath, lines.join('\n'), 'utf8');
}

function main() {
  if (!fs.existsSync(voiceRoot)) {
    console.warn('[vox-manifest] No Voice Audio or VoiceAudio folder found in app/data. Skipping.');
    return;
  }
  const baseManifest = collectBaseManifest();
  const skinManifest = collectSkinManifest();
  writeManifestModule(outFile, 'VOX_MANIFEST', baseManifest);
  writeManifestModule(skinOutFile, 'VOX_SKIN_MANIFEST', skinManifest);

  const skinFolderCount = Object.values(skinManifest).reduce(
    (n, skins) => n + Object.keys(skins).length,
    0
  );
  const skinFileCount = Object.values(skinManifest).reduce((total, skins) => {
    return (
      total +
      Object.values(skins).reduce((n, skin) => {
        return (
          n +
          Object.values(skin.subfolders || {}).reduce((m, sub) => m + (sub.files?.length || 0), 0)
        );
      }, 0)
    );
  }, 0);

  console.log(`[vox-manifest] base gods indexed: ${Object.keys(baseManifest).length}`);
  console.log(`[vox-manifest] skin folders indexed: ${skinFolderCount}`);
  console.log(`[vox-manifest] skin audio files indexed: ${skinFileCount}`);
  console.log(`[vox-manifest] wrote: ${path.relative(root, outFile)}`);
  console.log(`[vox-manifest] wrote: ${path.relative(root, skinOutFile)}`);
}

main();
